"""Generates docs/validation/report.md: how the engine compares with the proposal's prototype, ZARC, PAM and IMERG.

    python -m data validate report

Everything is computed from the database and the committed samples; nothing is tuned. The proposal's numbers are
quoted next to ours so that agreement and divergence are both visible. Concordance with ZARC is NOT independent
validation (ZARC is itself a water balance); the PAM check is weak evidence (municipal statistic, one point).
"""

import logging
import statistics
from datetime import date

import numpy as np
from sqlalchemy import select

from app.core.config import settings
from app.core.database import SessionLocal
from app.engines.dekads import planting_date
from app.engines.simulation import daily_et0, simulate_windows
from app.engines.water_balance import SOIL_THETA_AW, BalanceAssumptions, simulate_seasons
from app.engines.windows import ranking_score, spearman
from app.models.catalog import Crop
from app.models.geo import ClimateCell, Municipality
from app.models.reference import ZarcWindow
from app.repositories.climate import ClimateRepository
from app.repositories.reference import ReferenceRepository
from app.services.simulation_service import FIRST_SEASON, LAST_SEASON, cycle_for, load_climate
from data._common.paths import DATA_DIR, REPO_ROOT
from data.sources.earthdata_harmony.parse import read_giovanni_series

logger = logging.getLogger("data.validate.report")

PILOT_MUNICIPALITY = "2613008"
# Figures of the proposal's prototype (page 8), for comparison only.
PROTOTYPE = {
    "cowpea": {"spearman": 0.90, "inside": 79, "outside": 9, "top5": [12, 11, 13, 14, 15]},
    "peanut": {"spearman": 0.86, "inside": 63, "outside": 4, "top5": [12, 13, 11, 14, 10]},
    "sorghum": {"spearman": 0.82, "inside": 82, "outside": 15, "top5": [10, 11, 12, 13, 14]},
    "castor": {"spearman": -0.25, "inside": 5, "outside": 24, "top5": [10, 11, 9, 8, 7]},
}
SCENARIOS = {
    "base (proposal premises)": BalanceAssumptions(),
    "available water -25%": BalanceAssumptions(theta_aw=0.11 * 0.75),
    "available water +25%": BalanceAssumptions(theta_aw=0.11 * 1.25),
    "initial moisture 30%": BalanceAssumptions(initial_fraction=0.30),
    "initial moisture 100%": BalanceAssumptions(initial_fraction=1.00),
    "effective rain 80%": BalanceAssumptions(effective_rain_fraction=0.80),
}


def _table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def _zarc_indicator(window: ZarcWindow) -> list[float]:
    return [1.0 if v > 0 else 0.0 for v in window.values]


def run() -> str:
    out: list[str] = ["# Validation report", ""]
    out.append(
        "Generated by `python -m data validate report` from the database "
        f"(method `{settings.method_version}`, POWER 1984-2024, {FIRST_SEASON}-{LAST_SEASON} seasons). Nothing here is tuned. "
        "ZARC agreement shows consistency with the official method, not agronomic truth; PAM is a municipal statistic."
    )
    with SessionLocal() as session:
        climate_repo, reference = ClimateRepository(session), ReferenceRepository(session)
        municipality = session.get(Municipality, PILOT_MUNICIPALITY)
        cell = session.get(ClimateCell, municipality.power_cell_id)
        series = load_climate(climate_repo, cell)
        et0 = daily_et0(series)
        crops = {c.id: c for c in session.scalars(select(Crop).where(Crop.active.is_(True)))}

        # 1. ET0 and pilot reproduction
        annual_et0 = float(np.nanmean(et0[: (date(2023, 12, 31) - series.first_day).days + 1]) * 365.25)
        out += ["", "## 1. Pilot point (São Bento do Una, soil class 2, rainfed)", ""]
        out.append(
            f"Mean annual ET0 (FAO-56 Penman-Monteith, 1984-2023): **{annual_et0:.0f} mm** (proposal prototype: 1,646 mm). "
            f"Mean annual rain (POWER): **{np.nansum(series.rain[:14610]) / 40:.0f} mm** (proposal: about 950 mm)."
        )
        rows = []
        curves: dict[str, list[float]] = {}
        for crop_id, proto in PROTOTYPE.items():
            crop = crops[crop_id]
            results = simulate_windows(
                series, cycle_for(crop), FIRST_SEASON, LAST_SEASON, BalanceAssumptions(), et0=et0
            )
            p = [r.p for r in results]
            curves[crop_id] = p
            zarc = reference.zarc_for(PILOT_MUNICIPALITY, crop_id, 2)
            inside = outside = None
            rho = None
            if zarc:
                ind = _zarc_indicator(zarc)
                rho = spearman(p, ind)
                ins = [v for v, i in zip(p, ind, strict=True) if i]
                outs = [v for v, i in zip(p, ind, strict=True) if not i]
                inside, outside = 100 * statistics.fmean(ins), 100 * statistics.fmean(outs)
            top5 = sorted(range(36), key=lambda i: -p[i])[:5]
            rows.append(
                [
                    crop.name_en,
                    f"{rho:.2f}" if rho is not None else "n/a",
                    f"{proto['spearman']:+.2f}",
                    f"{inside:.0f}% / {outside:.0f}%" if inside is not None else "n/a",
                    f"{proto['inside']}% / {proto['outside']}%",
                    ", ".join(str(i + 1) for i in top5),
                    ", ".join(map(str, proto["top5"])),
                ]
            )
        out += ["", _table(
            ["Crop", "Spearman vs ZARC (ours)", "(prototype)", "mean p inside / outside ZARC window (ours)", "(prototype)", "top-5 dekads (ours)", "(prototype)"],
            rows,
        )]  # fmt: skip
        out += [
            "",
            "Castor fails as in the prototype: the engine's best dekads precede the ZARC window (a criterion the water balance "
            "does not see, e.g. rain at harvest, is the hypothesis). The cowpea cycle simulated here is the sum of the stage "
            "lengths (100 days) while the sheet's total says 110.",
        ]

        # 2. Gate
        out += [
            "",
            "## 2. Quality gate (Spearman of the 36 simulated frequencies vs the ZARC window, per location)",
            "",
        ]
        gate_rows = []
        for crop in sorted(crops.values(), key=lambda c: c.id):
            gate_rows.append(
                [crop.name_en, crop.gate_status, "" if crop.gate_value is None else f"{crop.gate_value:.2f}"]
            )
        out.append(_table(["Crop", "Statewide status (median)", "Median Spearman"], gate_rows))
        out += [
            "",
            f"Threshold {0.7}. The statewide median is informational: every analysis re-checks the crop at the chosen municipality "
            "and soil class, so a crop can be ranked where the engine agrees with ZARC (e.g. cowpea at the pilot) and excluded "
            "(`gate_failed`) elsewhere. Crops without ZARC rows are `not_run`.",
        ]

        # 3. Sensitivity
        out += ["", "## 3. Sensitivity of the ranking at the pilot (crops with a ZARC window)", ""]
        eligible = [c for c in crops.values() if c.has_zarc]
        base_scores: dict[str, float] = {}
        sens_rows = []
        for name, assumptions in SCENARIOS.items():
            scores = {}
            for crop in eligible:
                results = simulate_windows(series, cycle_for(crop), FIRST_SEASON, LAST_SEASON, assumptions, et0=et0)
                scores[crop.id] = ranking_score([r.p for r in results])
            if not base_scores:
                base_scores = scores
            ids = sorted(scores)
            rho = spearman([scores[i] for i in ids], [base_scores[i] for i in ids])
            order = sorted(scores, key=lambda c: (-scores[c], c))
            sens_rows.append([name, ", ".join(order[:3]), "1.00" if rho is None else f"{rho:.2f}"])
        out.append(_table(["Scenario", "Top 3 crops", "Rank correlation of crop scores with base"], sens_rows))
        out += ["", "A correlation near 1 means the crop ordering is stable under that assumption; the available-water and "
                "initial-moisture values are premises of the proposal, not measurements."]  # fmt: skip

        # 4. Rain source: IMERG vs POWER (2024, committed sample)
        out += ["", "## 4. Rain source: IMERG Final vs POWER (2024, pilot area)", ""]
        sample = DATA_DIR / "sources/earthdata_harmony/sample/imerg_final_serie_2024_ponto_agreste_PE.csv"
        _, imerg = read_giovanni_series(sample)
        offset = (date(2024, 1, 1) - series.first_day).days
        power_2024 = series.rain[offset : offset + 366]
        imerg_2024 = np.array(
            [imerg[date.fromordinal(date(2024, 1, 1).toordinal() + i)] for i in range(366)], dtype=float
        )
        corr = float(np.corrcoef(power_2024, imerg_2024)[0, 1])
        out.append(
            f"2024 total: POWER **{power_2024.sum():.0f} mm**, IMERG **{imerg_2024.sum():.0f} mm** "
            f"({100 * (1 - imerg_2024.sum() / power_2024.sum()):.0f}% less); daily correlation {corr:.2f}. "
            "The sources disagree strongly, so the app shows POWER as its source and states the dependency."
        )
        cowpea = cycle_for(crops["cowpea"])
        et0_2024 = et0[offset : offset + 366]
        start = (planting_date(2024, 12) - date(2024, 1, 1)).days
        ratios = {}
        for label, rain in (("POWER", power_2024), ("IMERG", imerg_2024)):
            window = slice(start, start + cowpea.length)
            outcome = simulate_seasons(rain[window][None, :], et0_2024[window][None, :], cycle_for(crops["cowpea"]))
            ratios[label] = float(outcome.eta_etc[0])
        out.append(
            f"Effect on one season (cowpea planted in dekad 12 of 2024): ETa/ETc = {ratios['POWER']:.2f} with POWER rain, "
            f"{ratios['IMERG']:.2f} with IMERG rain (success needs 0.80)."
        )

        # 5. PAM check
        out += ["", "## 5. Independent check against PAM yields (weak evidence)", ""]
        cowpea_crop = crops["cowpea"]
        years = list(range(2005, 2024))
        per_year = []
        for y in years:
            begin = (planting_date(y, 12) - series.first_day).days
            win = slice(begin, begin + cowpea.length)
            outcome = simulate_seasons(series.rain[win][None, :], et0[win][None, :], cycle_for(cowpea_crop))
            per_year.append(float(outcome.eta_etc[0]))
        pam = dict(reference.pam_series(PILOT_MUNICIPALITY, cowpea_crop.pam_crop))
        paired = [(e, pam[y]) for y, e in zip(years, per_year, strict=True) if y in pam]
        rho = spearman([a for a, _ in paired], [b for _, b in paired]) if len(paired) > 3 else None
        out.append(
            f"Cowpea planted in dekad 12 each year, seasonal ETa/ETc vs PAM bean yield of the municipality, {len(paired)} years: "
            f"rank correlation **{'n/a' if rho is None else f'{rho:+.2f}'}** (proposal: +0.33 with the municipality, +0.48 with "
            "the state median, 19 years, 21 April planting). PAM pools all bean types and mixes rainfed and irrigated areas."
        )

        out += ["", "## Assumptions behind these numbers", "",
                f"- Available water per soil class: {SOIL_THETA_AW} m³/m³ (class 2 = proposal premise; 1 and 3 are project assumptions).",
                "- Initial moisture 60% of available water, effective rain equals rain, no irrigation.",
                "- Success: ETa/ETc ≥ 0.80 and mid-season (flowering) deficit < 25 mm. Dekad 1 = Jan 1-10 (unconfirmed).",
                "- Kc and root depth curves are assumptions recorded in `crop_parameter_sources`."]  # fmt: skip

    text = "\n".join(out) + "\n"
    target = REPO_ROOT / "docs" / "validation" / "report.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    logger.info("validation report -> %s", target)
    return text
